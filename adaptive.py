def rerank(scores_by_name, answers):
    """Детерминированная коррекция скоров по ответам второго тура.
    scores_by_name: {имя класса: score}; answers: {ключ вопроса: фраза}.
    Возвращает новый словарь, скоры клипуются в [0, 1]."""
    out = {str(n): float(s) for n, s in (scores_by_name or {}).items()}
    answers = {k: _ANSWER_CANON.get((k, (v or "").strip().lower()), v)
            for k, v in (answers or {}).items()}
    for key, phrase in (answers or {}).items():
        for (k, p), deltas in HEAD_ADJUST.items():
            if key == k and (phrase or "") == p:
                for name, d in deltas:
                    if name in out:
                        out[name] = min(1.0, max(0.0, out[name] + d))
    # триада отрицательных различителей — согласованная картина ГБН
    _HEAD_NO_TRIAD = {"head_neck": "подбородок к груди прижимается свободно",
                      "head_light": "светобоязни нет, звуки не раздражают",
                      "head_veg": "давление не скачет, шума в ушах и накатывающей слабости нет"}
    if all((answers or {}).get(k) == p for k, p in _HEAD_NO_TRIAD.items()) \
            and "головная боль напряжения" in out:
        out["головная боль напряжения"] = min(1.0, out["головная боль напряжения"] + 0.05)
    return out


def enrich_query(query, answers):
    """Обогащение текста каноническими фразами (переопределяет старую версию)."""
    parts = []
    for k, v in (answers or {}).items():
        v = (v or '').strip().lower()
        parts.append(_ANSWER_CANON.get((k, (v or "").strip().lower()), str(v)))
    return (query or '').strip() + '. ' + '. '.join(parts)


def _ans_val(v):
    """Фраза ответа из кортежа-опции; строку возвращает как есть."""
    if isinstance(v, (tuple, list)):
        return str(v[1]) if len(v) > 1 else str(v[0])
    return str(v)


