def _pick(group, max_q):
    return [item[:3] for item in sorted(group["questions"], key=lambda x: not x[3])][:max_q]

def get_followups(query, top_names, max_q=3):
    q = (query or "").lower().replace("ё", "е")
    tops = [(n or "").lower() for n in (top_names or [])[:5]]
    # 1) явный ключ в самом запросе — самый сильный сигнал
    for group in QUESTION_BANK:
        if any(k in q for k in group["match_any"]):
            return _pick(group, max_q)
    # 2) кластер кандидатов: минимум 2 из топ-3 указывают на одну группу
    for group in QUESTION_BANK:
        if sum(any(k in n for k in group["match_any"]) for n in tops[:3]) >= 2:
            return _pick(group, max_q)
    # 3) одиночный лидер не заслуживает доверия — общие вопросы
    return [item[:3] for item in GENERIC_QUESTIONS]

def enrich_query(query, answers):
    parts = [query.strip().rstrip(".")]
    for key, phrase in (answers or {}).items():
        if phrase:
            parts.append(phrase)
    return ". ".join(parts)

def render_followups(query, top_names):
    qs = get_followups(query, top_names)
    if not qs or not ADAPTIVE_ENABLED:
        return None
    if st.session_state.get("adaptive_done_for") == query:
        return None
    st.markdown("### ❓ Уточните — это заметно улучшит точность")
    answers = {}
    with st.form("adaptive_form"):
        for key, text, opts in qs:
            answers[key] = st.radio(text, opts, index=None,
                                    format_func=lambda p: p[0], key=f"af_{key}")
        col1, col2 = st.columns(2)
        submit = col1.form_submit_button("Уточнить и пересчитать")
        skip = col2.form_submit_button("Пропустить")
    if skip:
        st.session_state["adaptive_done_for"] = query
        return None
    if submit and any(v for v in answers.values()):
        st.session_state["adaptive_done_for"] = query
        return enrich_query(query, {k: v[1] for k, v in answers.items() if v})
    return None
